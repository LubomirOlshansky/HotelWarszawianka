"""The shared reference-photo store: one place every thread can look, with an index ranked like the inventory.
    python3 -I tools/refs_store.py index                     # scan the store, write INDEX.md and INDEX.json into it
    python3 -I tools/refs_store.py gaps [--n=30] [--tier=S,A,B,M]   # ranked places with no photo or no ortho: the Mac gather list
    python3 -I tools/refs_store.py show SLUG                 # what the store holds for one place
    python3 -I tools/refs_store.py where TEXT                # slugs whose slug or place name contains TEXT
    python3 -I tools/refs_store.py pull SLUG... | --all      # store <slug>/ into the repo's refs/<slug>/ (the working copy)
    python3 -I tools/refs_store.py push SLUG... | --all [--force]   # repo refs/<slug>/ into the store, then index
    python3 -I tools/refs_store.py --selftest                # fake store, inventory and repo in a temp dir: prints `refs_store: OK`
Options (before or after the command): --store=DIR (else env REFS_STORE, else /mnt/project-files/refs/),
--inventory=FILE, --slugs=FILE, --repo-refs=DIR (the last three are for the selftest).

Reference photos of real buildings are modelling reference only: never committed, never shipped
(model-from-photos skill). They used to live in the gitignored refs/<slug>/ of whichever machine gathered
them, mostly the Mac, so cloud threads could not see them. The home is now the project's shared folder
(a network mount, not mounted on the Mac): /mnt/project-files/refs/<slug>/ with photos (jpg jpeg png webp heic),
street/ (tools/street_photos.py), ortho*.jpg|png, SOURCES.md, REPORT.md; at the root README.md, INDEX.md and
INDEX.json (generated here) and ALIASES.tsv (kept by hand or by an agent: slug TAB path relative to
/mnt/project-files TAB note, `#` comments; it points at photo folders that already exist elsewhere in the
shared folder, so nothing is duplicated; a slug may have several lines). The repo's refs/<slug>/ stays the
local working copy every tool and skill already uses; this tool syncs the two.

Slug = the site key in game/scripts/landmarks.gd (same as docs/landmarks/specs/<slug>.md) when there is one,
else a short snake_case name. The index follows the rank in docs/CITY_INVENTORY.md Part 1; inventory rows carry
no slug, so tools/refs_slugs.tsv (slug TAB place cell exactly as in the inventory, names only, committed) ties them.

Copy rules (both ways): nothing is ever deleted; a file of equal size is skipped; a file that exists with a
different size is a conflict: the destination is kept, it is printed and counted, the exit code stays 0
(--force overwrites); SOURCES.md is special: when both exist and differ, the lines the source has and the
destination lacks are appended to the destination. Dotfiles and .DS_Store are skipped.

Network-mount care: only the store and the alias paths are listed (alias scan at most 3 levels deep); the
mount's root is never walked. Standard library only.
"""

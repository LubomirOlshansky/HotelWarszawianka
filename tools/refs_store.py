def build_parser():
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--store")
    common.add_argument("--inventory")
    common.add_argument("--slugs")
    common.add_argument("--repo-refs", dest="repo_refs")
    p = argparse.ArgumentParser(prog="refs_store.py", description=__doc__.split("\n")[0])
    p.add_argument("--selftest", action="store_true")
    sub = p.add_subparsers(dest="cmd")
    sub.add_parser("index", parents=[common])
    g = sub.add_parser("gaps", parents=[common])
    g.add_argument("--n", type=int, default=30)
    g.add_argument("--tier")
    s = sub.add_parser("show", parents=[common])
    s.add_argument("slug")
    w = sub.add_parser("where", parents=[common])
    w.add_argument("text")
    for name in ("pull", "push"):
        c = sub.add_parser(name, parents=[common])
        c.add_argument("slugs_list", nargs="*", metavar="SLUG")
        c.add_argument("--all", action="store_true")
        c.add_argument("--force", action="store_true")
    return p


def main(argv=None):
    p = build_parser()
    args = p.parse_args(argv)
    if args.selftest:
        return selftest()
    if args.cmd == "index":
        return cmd_index(args)
    if args.cmd == "gaps":
        return cmd_gaps(args)
    if args.cmd == "show":
        return cmd_show(args)
    if args.cmd == "where":
        return cmd_where(args)
    if args.cmd in ("pull", "push"):
        return sync_command(args, args.cmd)
    p.print_usage()
    return 1


if __name__ == "__main__":
    sys.exit(main())

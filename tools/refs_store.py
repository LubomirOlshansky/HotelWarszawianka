def selftest():
    fails = []

    def check(cond, what):
        if not cond:
            fails.append(what)

    def touch(path, size=10, text=None):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(text.encode("utf-8") if text is not None else b"x" * size)

    def run(*argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = main(list(argv))
        return code, out.getvalue(), err.getvalue()

    with tempfile.TemporaryDirectory() as tmp:
        shared = os.path.join(tmp, "shared")
        store = os.path.join(shared, "refs")
        repo = os.path.join(tmp, "repo_refs")
        inv = os.path.join(tmp, "inv.md")
        smap = os.path.join(tmp, "slugs.tsv")
        with open(inv, "w", encoding="utf-8") as f:
            f.write("""# Inventory
## Part 1. The ranked list

### Tier S: faces

| # | Place | Street | Kind | Status | Next |
| --- | --- | --- | --- | --- | --- |
| 1 | Alpha Palace | A street | landmark | ★ | none |
| 2 | Bęta Hall (OSM: Beta) | B street | hall | ◐ | photo check |

### Tier A: iconic

| # | Place | Street | Kind | Status | Next |
| --- | --- | --- | --- | --- | --- |
| 3 | Gamma Tower | C street | tower | ✗ | site `gamma` |

### Tier B: characteristic

| # | Place | Street | Kind | Status | Next |
| --- | --- | --- | --- | --- | --- |
| 4 | Delta House | D street | house | ○ | none |

### Warsaw modernism and brutalism

| # | Place | Street | Kind | Status | Next |
| --- | --- | --- | --- | --- | --- |
| 5 | Mod Block | M street | block | ✗ | none |

## Part 3. Other

| 9 | Not Part One | x | x | x | x |
""")
        with open(smap, "w", encoding="utf-8") as f:
            f.write("# slug\tplace\nalpha\tAlpha Palace\nbeta\tBęta Hall (OSM: Beta)\ngamma\tGamma Tower\nghost\tNo Such Place\n")
        # the store: alpha has everything, orphan matches no row, beta only through an alias
        for n in ("a1.jpg", "a2.PNG", "a3.heic"):
            touch(os.path.join(store, "alpha", n))
        touch(os.path.join(store, "alpha", "street", "s1.jpg"))
        touch(os.path.join(store, "alpha", "ortho_2.png"))
        touch(os.path.join(store, "alpha", ".DS_Store"))
        touch(os.path.join(store, "alpha", "REPORT.md"), text="# report\n")
        touch(os.path.join(store, "alpha", "SOURCES.md"), text="line one\nline two\n")
        touch(os.path.join(store, "orphan", "o1.webp"))
        for n in ("b1.jpg", "b2.jpg"):
            touch(os.path.join(shared, "elsewhere", "beta_photos", n))
        touch(os.path.join(shared, "elsewhere", "beta_photos", "deep", "b3.jpg"))
        touch(os.path.join(shared, "elsewhere", "beta_photos", "d1", "d2", "d3", "b4.jpg"))  # three levels below: counted
        touch(os.path.join(shared, "elsewhere", "beta_photos", "d1", "d2", "d3", "d4", "b5.jpg"))  # four levels: not counted
        touch(os.path.join(shared, "elsewhere", "beta_photos", "notes.txt"))
        with open(os.path.join(store, "ALIASES.tsv"), "w", encoding="utf-8") as f:
            f.write("# slug\tpath\tnote\nbeta\telsewhere/beta_photos\tF's folder\nbeta\t../outside\tmust be refused\nzed\tnowhere\t\n")
        common = ["--store=" + store, "--inventory=" + inv, "--slugs=" + smap, "--repo-refs=" + repo]

        code, out, err = run("index", *common)
        check(code == 0, "index exit code")
        check("ghost" in err and "matches no inventory row" in err, "warning for a map line without a row")
        data = json.load(open(os.path.join(store, "INDEX.json"), encoding="utf-8"))
        invd = {x["rank"]: x for x in data["inventory"]}
        check(len(data["inventory"]) == 5, "five Part 1 rows (Part 3 excluded): %d" % len(data["inventory"]))
        check([x["tier"] for x in data["inventory"]] == ["S", "S", "A", "B", "M"], "tiers S S A B M")
        a = invd[1]
        check(a["slug"] == "alpha" and a["photos"] == 3 and a["street_photos"] == 1 and a["ortho"] and a["report"],
              "alpha counts: %r" % a)
        b = invd[2]
        check(b["photos"] == 0 and b["more_count"] == 4 and not b["ortho"], "beta via alias, depth limit: %r" % b)
        check(b["more_paths"] == ["elsewhere/beta_photos", "../outside"], "alias paths listed: %r" % b["more_paths"])
        check(invd[3]["slug"] == "gamma" and not invd[3]["in_store"], "gamma mapped, no folder")
        check(invd[4]["slug"] is None, "unmapped row has no slug")
        un = {x["slug"]: x for x in data["unmatched"]}
        check(set(un) == {"orphan", "zed"} and un["orphan"]["photos"] == 1 and un["zed"]["source"] == "alias",
              "unmatched table: %r" % sorted(un))
        md = open(os.path.join(store, "INDEX.md"), encoding="utf-8").read()
        check("| 1 | S | Alpha Palace | alpha | 3 | 1 | yes | yes | - | ★ |" in md, "INDEX.md alpha row")
        check(md.index("Alpha Palace") < md.index("Gamma Tower") < md.index("Mod Block"), "INDEX.md in rank order")
        check(os.path.exists(os.path.join(store, "README.md")), "README.md written")
        check(not os.path.exists(os.path.join(store, "ALIASES.tsv.tmp")), "no temp files left")

        code, out, _ = run("gaps", "--n=10", *common)
        lines = [ln for ln in out.splitlines() if ln[:3].strip().isdigit()]
        check(code == 0 and [ln.split()[0] for ln in lines] == ["2", "3", "4", "5"], "gaps list: %r" % out)
        check("no ortho" in lines[0] and "no photos" not in lines[0], "beta lacks only an ortho")
        check("no photos + no ortho" in lines[1], "gamma lacks both")
        code, out, _ = run("gaps", "--n=1", "--tier=A,B", *common)
        check(len([ln for ln in out.splitlines() if ln[:3].strip().isdigit()]) == 1 and "Gamma" in out, "gaps --n and --tier")
        code, out, _ = run("gaps", "--store=" + os.path.join(tmp, "nope"))
        check(code == 1 and "no store" in out and len(out.strip().splitlines()) == 1, "gaps without a store: one line, exit 1")

        code, out, _ = run("show", "alpha", *common)
        check(code == 0 and "a1.jpg" in out and "line one" in out and "Alpha Palace" in out, "show alpha")
        code, out, _ = run("show", "beta", *common)
        check(code == 0 and "elsewhere/beta_photos" in out and "4 images" in out, "show beta alias")
        check(run("show", "nothing", *common)[0] == 1, "show of nothing exits 1")
        code, out, _ = run("where", "BETA", *common)
        check(code == 0 and "beta" in out and "Bęta" in out, "where is case-insensitive")
        code, out, _ = run("where", "bet", *common)
        check("Bęta" in out, "where ignores diacritics")
        code, out, _ = run("where", "orph", *common)
        check("orphan" in out, "where finds a store-only slug")

        # pull
        code, out, _ = run("pull", "alpha", *common)
        check(code == 0 and os.path.exists(os.path.join(repo, "alpha", "street", "s1.jpg")), "pull copies tree")
        check(not os.path.exists(os.path.join(repo, "alpha", ".DS_Store")), "pull skips dotfiles")
        check("0 conflicts" in out and "7 copied" in out, "pull summary: %r" % out)
        code, out, _ = run("pull", "alpha", *common)
        check("0 copied" in out and "0 conflicts" in out, "second pull skips equal sizes: %r" % out)
        touch(os.path.join(repo, "alpha", "a1.jpg"), size=99)
        code, out, _ = run("pull", "alpha", *common)
        check(code == 0 and "1 conflicts" in out and os.path.getsize(os.path.join(repo, "alpha", "a1.jpg")) == 99,
              "conflict keeps the destination, exit 0: %r" % out)
        code, out, _ = run("pull", "alpha", "--force", *common)
        check(os.path.getsize(os.path.join(repo, "alpha", "a1.jpg")) == 10, "--force overwrites")
        check(run("pull", "alpha", "--store=" + os.path.join(tmp, "nope"))[0] == 1, "pull without a store exits 1")
        check(run("pull", "ghostfolder", *common)[0] == 1, "pull of a missing slug exits 1")
        # SOURCES.md append, both ways, never deleting
        touch(os.path.join(repo, "alpha", "SOURCES.md"), text="line two\nmac line\n")
        code, out, _ = run("push", "alpha", *common)
        src = open(os.path.join(store, "alpha", "SOURCES.md"), encoding="utf-8").read()
        check(src == "line one\nline two\nmac line\n", "push appends the Mac's new lines to SOURCES.md: %r" % src)
        check(code == 0 and "1 SOURCES.md lines appended" in out, "push summary: %r" % out)
        code, out, _ = run("push", "alpha", *common)
        check("0 SOURCES.md lines appended" in out, "second push appends nothing")
        # push a new slug, index follows
        touch(os.path.join(repo, "newone", "n1.jpg"))
        touch(os.path.join(repo, "newone", "n2.jpg"), size=5)
        touch(os.path.join(repo, "newone", ".hidden"))
        code, out, _ = run("push", "newone", *common)
        check(code == 0 and os.path.exists(os.path.join(store, "newone", "n2.jpg")), "push copies")
        check(not os.path.exists(os.path.join(store, "newone", ".hidden")), "push skips dotfiles")
        data = json.load(open(os.path.join(store, "INDEX.json"), encoding="utf-8"))
        check("newone" in {x["slug"] for x in data["unmatched"]}, "push re-runs index")
        touch(os.path.join(repo, "newone", "n1.jpg"), size=77)
        code, out, _ = run("push", "--all", *common)
        check(code == 0 and "1 conflicts" in out and os.path.getsize(os.path.join(store, "newone", "n1.jpg")) == 10,
              "push conflict keeps the store's file: %r" % out)
        check(len(os.listdir(os.path.join(store, "alpha"))) == len(os.listdir(os.path.join(repo, "alpha"))) + 1,
              "nothing deleted (store keeps its .DS_Store)")
        check(run("push", "../escape", *common)[0] == 1, "push refuses a path as slug")
        # a new store is created by push and gets a README
        fresh = os.path.join(tmp, "fresh", "refs")
        code, out, _ = run("push", "alpha", "--store=" + fresh, "--inventory=" + inv, "--slugs=" + smap, "--repo-refs=" + repo)
        check(code == 0 and os.path.exists(os.path.join(fresh, "README.md")) and os.path.exists(os.path.join(fresh, "INDEX.json")),
              "push creates the store, README and index")
        check(not os.path.exists(os.path.join(fresh, "ALIASES.tsv")), "the tool never writes ALIASES.tsv")
        code, out, _ = run("index", "--store=" + os.path.join(tmp, "fresh2", "refs"), "--inventory=" + inv, "--slugs=" + smap)
        check(code == 0 and "0 with photos" in out, "index creates an empty store and treats absent ALIASES.tsv as empty")
    if fails:
        for f in fails:
            print("refs_store: FAIL: " + f)
        return 1
    print("refs_store: OK")
    return 0



# ---------------------------------------------------------------- helpers

def more_cell(x):
    """The index's More cell: the count and the first alias path; every path is in INDEX.json."""
    rest = len(x["more_paths"]) - 1
    return "%d (%s%s)" % (x["more_count"], x["more_paths"][0], ", +%d more in INDEX.json" % rest if rest else "")


def norm(s):
    """Lowercase, no diacritics (ł included): for matching names."""
    s = s.replace("ł", "l").replace("Ł", "L")
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if not unicodedata.combining(c)).lower()


def is_img(name):
    return name.lower().endswith(IMG_EXT)


def is_ortho(name):
    n = name.lower()
    return n.startswith("ortho") and n.endswith((".jpg", ".jpeg", ".png"))


def skip_name(name):
    return name.startswith(".")


def entries(path):
    """scandir names of one folder, sorted; [] when it cannot be listed."""
    try:
        with os.scandir(path) as it:
            return sorted(it, key=lambda e: e.name)
    except OSError:
        return []


def read_lines(path):
    try:
        with open(path, encoding="utf-8") as f:
            return f.read().splitlines()
    except OSError:
        return []


def tsv_rows(path):
    """Non-empty, non-comment lines of a TSV file as lists of stripped cells."""
    out = []
    for ln in read_lines(path):
        if not ln.strip() or ln.lstrip().startswith("#"):
            continue
        out.append([c.strip() for c in ln.split("\t")])
    return out


def store_dir(args):
    return args.store or os.environ.get("REFS_STORE") or DEFAULT_STORE


def store_base(store):
    """The folder alias paths are relative to: the store's parent (/mnt/project-files)."""
    return os.path.dirname(os.path.normpath(store))


# ---------------------------------------------------------------- inventory

def parse_inventory(path):
    """Part 1 rows in rank order: dicts rank, tier, place, street, kind, status, next."""
    rows, tier, in_part1 = [], "", False
    for ln in read_lines(path):
        if ln.startswith("## "):
            in_part1 = ln.startswith("## Part 1")
            continue
        if not in_part1:
            continue
        if ln.startswith("### "):
            m = re.match(r"### Tier ([SAB])\b", ln)
            tier = m.group(1) if m else ("M" if ln.startswith("### Warsaw modernism") else "")
            continue
        m = re.match(r"\|\s*(\d+)\s*\|", ln)
        if not m or not tier:
            continue
        cells = [c.strip() for c in ln.strip().strip("|").split(" | ")]
        if len(cells) < 5:
            continue
        rows.append({"rank": int(cells[0]), "tier": tier, "place": cells[1], "street": cells[2], "kind": cells[3],
                     "status": cells[4], "next": " | ".join(cells[5:])})
    return rows


def load_slug_map(path, rows):
    """{place text: slug} joined to the inventory; warns about lines that match no row."""
    by_place = {r["place"]: r for r in rows}
    by_norm = {norm(r["place"]): r for r in rows}
    for rec in tsv_rows(path):
        if len(rec) < 2 or not rec[0] or not rec[1]:
            print("refs_store: warning: slug map line without two cells: %r" % "\t".join(rec), file=sys.stderr)
            continue
        slug, place = rec[0], rec[1]
        row = by_place.get(place) or by_norm.get(norm(place))
        if row is None:
            print("refs_store: warning: slug map %s: place matches no inventory row: %s" % (slug, place), file=sys.stderr)
            continue
        row["slug"] = slug
    for r in rows:
        r.setdefault("slug", "")
    return rows


# ---------------------------------------------------------------- store scan

def scan_folder(path):
    """What one slug folder holds: photo counts, ortho, report, sources. Photos in subfolders count
    too (ALIAS_DEPTH levels; the Mac's folders keep sets like `distant/` or `commons/`), `street/` apart."""
    res = {"photos": 0, "street_photos": 0, "ortho": False, "report": False, "sources": False}

    def walk(p, depth, key):
        for e in entries(p):
            if skip_name(e.name):
                continue
            if e.is_dir(follow_symlinks=False):
                if depth < ALIAS_DEPTH:
                    walk(e.path, depth + 1, "street_photos" if depth == 0 and e.name.lower() == "street" else key)
                continue
            if is_ortho(e.name):
                res["ortho"] = True
            elif is_img(e.name):
                res[key] += 1
            if depth == 0 and e.name == "REPORT.md":
                res["report"] = True
            if depth == 0 and e.name == "SOURCES.md":
                res["sources"] = True

    walk(path, 0, "photos")
    return res


def scan_alias(base, rel):
    """Images (and orthos) under base/rel, listing at most ALIAS_DEPTH levels below it."""
    rel = rel.strip().strip("/")
    full = os.path.normpath(os.path.join(base, rel))
    res = {"path": rel, "images": 0, "ortho": False, "exists": False}
    if not rel or ".." in rel.split("/") or not (full + "/").startswith(base.rstrip("/") + "/") or full == base.rstrip("/"):
        return res
    if os.path.isfile(full):
        res["exists"] = True
        res["images"] = 1 if is_img(full) else 0
        res["ortho"] = is_ortho(os.path.basename(full))
        return res
    if not os.path.isdir(full):
        return res
    res["exists"] = True

    def walk(p, depth):
        for e in entries(p):
            if skip_name(e.name):
                continue
            if e.is_dir(follow_symlinks=False):
                if depth < ALIAS_DEPTH:
                    walk(e.path, depth + 1)
            elif is_img(e.name):
                res["images"] += 1
                if is_ortho(e.name):
                    res["ortho"] = True

    walk(full, 0)
    return res


def load_aliases(store):
    """{slug: [alias dicts]} from ALIASES.tsv (absent or partial = what can be read)."""
    base = store_base(store)
    out = {}
    for rec in tsv_rows(os.path.join(store, "ALIASES.tsv")):
        if len(rec) < 2 or not rec[0] or not rec[1]:
            continue
        a = scan_alias(base, rec[1])
        a["note"] = rec[2] if len(rec) > 2 else ""
        out.setdefault(rec[0], []).append(a)
    return out


def scan_store(store):
    """{slug: folder info} for every folder in the store that is a place: not a dot folder and not
    an underscore folder (`_f/`, `_mac-root/`: whole collections, reached through ALIASES.tsv)."""
    out = {}
    for e in entries(store):
        if skip_name(e.name) or e.name.startswith("_") or not e.is_dir(follow_symlinks=False):
            continue
        out[e.name] = scan_folder(e.path)
    return out


def entry_for(slug, folders, aliases):
    f = folders.get(slug, {"photos": 0, "street_photos": 0, "ortho": False, "report": False, "sources": False})
    al = aliases.get(slug, [])
    more_paths = [a["path"] for a in al]
    return {"photos": f["photos"], "street_photos": f["street_photos"],
            "ortho": bool(f["ortho"] or any(a["ortho"] for a in al)), "ortho_own": bool(f["ortho"]),
            "report": bool(f["report"]), "sources": bool(f["sources"]), "in_store": slug in folders,
            "more_count": sum(a["images"] for a in al), "more_paths": more_paths}


def build_index(store, rows):
    folders = scan_store(store)
    aliases = load_aliases(store)
    inv = []
    for r in rows:
        e = entry_for(r["slug"], folders, aliases) if r["slug"] else entry_for("", {}, {})
        inv.append({"rank": r["rank"], "tier": r["tier"], "place": r["place"], "street": r["street"], "kind": r["kind"],
                    "status": r["status"], "slug": r["slug"] or None, **e})
    mapped = {r["slug"] for r in rows if r["slug"]}
    unmatched = []
    for slug in sorted(set(folders) | set(aliases)):
        if slug in mapped:
            continue
        e = entry_for(slug, folders, aliases)
        e["slug"] = slug
        e["source"] = "store" if slug in folders else "alias"
        unmatched.append(e)
    return inv, unmatched


def total_photos(e):
    return e["photos"] + e["street_photos"] + e["more_count"]


# ---------------------------------------------------------------- commands: index, gaps, show, where

def yn(b):
    return "yes" if b else "no"


def cell(s):
    return s.replace("|", "/")


def render_index(inv, unmatched, store):
    today = datetime.date.today().isoformat()
    mapped = [x for x in inv if x["slug"]]
    with_photos = [x for x in inv if total_photos(x) > 0]
    with_ortho = [x for x in inv if x["ortho"]]
    n_files = sum(x["photos"] + x["street_photos"] for x in {x["slug"]: x for x in mapped}.values())
    n_files += sum(x["photos"] + x["street_photos"] for x in unmatched if x["source"] == "store")
    L = ["# Reference photo index", "",
         "Generated by `python3 -I tools/refs_store.py index` on %s. Do not edit; run `index` again." % today, "",
         "Photos of real buildings and places, for modelling reference only: never committed to git, never shipped.",
         "Places are in the rank order of docs/CITY_INVENTORY.md Part 1. `slug` is the folder `refs/<slug>/` in this store",
         "(the site key in game/scripts/landmarks.gd; `-` = no slug tied yet in tools/refs_slugs.tsv). `Photos` counts",
         "the folder's own photos, `Street` the ones in `street/`, `More` the images under the slug's lines in ALIASES.tsv.",
         "Look here first; `python3 -I tools/refs_store.py pull SLUG` copies a folder into the repo's refs/.", "",
         "Totals: %d ranked places, %d with a slug, %d with photos (own or aliased), %d with an orthophoto, %d with a report; "
         "%d photo files in %d store folders." % (len(inv), len(mapped), len(with_photos), len(with_ortho),
                                                 sum(1 for x in inv if x["report"]), n_files,
                                                 sum(1 for x in inv if x["in_store"]) + sum(1 for x in unmatched if x["source"] == "store")),
         "", "## Ranked places", "",
         "| Rank | Tier | Place | Slug | Photos | Street | Ortho | Report | More | Status |",
         "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for x in inv:
        more = "-"
        if x["more_paths"]:
            more = more_cell(x)
        L.append("| %d | %s | %s | %s | %d | %d | %s | %s | %s | %s |" % (
            x["rank"], x["tier"], cell(x["place"]), x["slug"] or "-", x["photos"], x["street_photos"], yn(x["ortho"]),
            yn(x["report"]), cell(more), x["status"]))
    L += ["", "## Folders and aliases with no inventory row", ""]
    if unmatched:
        L += ["| Slug | Where | Photos | Street | Ortho | Report | More |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for x in unmatched:
            more = more_cell(x) if x["more_paths"] else "-"
            L.append("| %s | %s | %d | %d | %s | %s | %s |" % (x["slug"], x["source"], x["photos"], x["street_photos"],
                                                          yn(x["ortho"]), yn(x["report"]), cell(more)))
    else:
        L.append("None.")
    return "\n".join(L) + "\n"


def write_atomic(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def cmd_index(args):
    store = store_dir(args)
    os.makedirs(store, exist_ok=True)
    readme = os.path.join(store, "README.md")
    if not os.path.exists(readme):
        write_atomic(readme, README)
    rows = load_slug_map(args.slugs or SLUG_MAP, parse_inventory(args.inventory or INVENTORY))
    inv, unmatched = build_index(store, rows)
    write_atomic(os.path.join(store, "INDEX.md"), render_index(inv, unmatched, store))
    data = {"generated": datetime.date.today().isoformat(), "inventory": inv, "unmatched": unmatched}
    write_atomic(os.path.join(store, "INDEX.json"), json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    mapped = sum(1 for x in inv if x["slug"])
    print("refs_store: index: %d ranked places (%d with a slug, %d with photos, %d with ortho), %d unmatched folders/aliases -> %s"
          % (len(inv), mapped, sum(1 for x in inv if total_photos(x) > 0), sum(1 for x in inv if x["ortho"]), len(unmatched),
             os.path.join(store, "INDEX.md")))
    return 0


def need_store(args):
    store = store_dir(args)
    if not os.path.isdir(store):
        print("refs_store: no store at %s (set --store or REFS_STORE; `index` or `push` creates it)" % store)
        return None
    return store


def cmd_gaps(args):
    store = need_store(args)
    if store is None:
        return 1
    tiers = [t.strip().upper() for t in (args.tier or "").split(",") if t.strip()] or list(TIERS)
    rows = load_slug_map(args.slugs or SLUG_MAP, parse_inventory(args.inventory or INVENTORY))
    inv, _ = build_index(store, rows)
    shown = 0
    for x in inv:
        if x["tier"] not in tiers:
            continue
        miss = []
        if total_photos(x) == 0:
            miss.append("no photos")
        if not x["ortho"]:
            miss.append("no ortho")
        if not miss:
            continue
        print("%3d  %s  %-60s  %-18s  %s  %s" % (x["rank"], x["tier"], x["place"][:60], x["slug"] or "(no slug)",
                                               " + ".join(miss), x["status"]))
        shown += 1
        if shown >= args.n:
            break
    print("refs_store: gaps: %d shown (tiers %s, n=%d)" % (shown, ",".join(tiers), args.n))
    return 0


def cmd_show(args):
    store = need_store(args)
    if store is None:
        return 1
    slug = args.slug
    folders = scan_store(store)
    aliases = load_aliases(store)
    rows = load_slug_map(args.slugs or SLUG_MAP, parse_inventory(args.inventory or INVENTORY))
    places = [r for r in rows if r["slug"] == slug]
    if slug not in folders and slug not in aliases:
        print("refs_store: nothing in the store for %s" % slug)
        return 1
    for r in places:
        print("place: #%d %s (tier %s, %s)" % (r["rank"], r["place"], r["tier"], r["status"]))
    if slug in folders:
        f = folders[slug]
        print("folder: %s (%d photos, %d street, ortho %s, report %s, sources %s)" % (
            os.path.join(store, slug), f["photos"], f["street_photos"], yn(f["ortho"]), yn(f["report"]), yn(f["sources"])))
        names = [e.name for e in entries(os.path.join(store, slug)) if not skip_name(e.name)]
        for n in names[:40]:
            print("  " + n)
        if len(names) > 40:
            print("  ... %d more" % (len(names) - 40))
    for a in aliases.get(slug, []):
        print("alias: %s  %d images%s%s  %s" % (a["path"], a["images"], ", ortho" if a["ortho"] else "",
                                              "" if a["exists"] else "  (path not found)", a["note"]))
    src = read_lines(os.path.join(store, slug, "SOURCES.md"))
    if src:
        print("SOURCES.md (first lines):")
        for ln in src[:6]:
            print("  " + ln[:160])
    return 0


def cmd_where(args):
    store = store_dir(args)
    rows = load_slug_map(args.slugs or SLUG_MAP, parse_inventory(args.inventory or INVENTORY))
    q = norm(args.text)
    found = {}
    for r in rows:
        if q in norm(r["place"]) or (r["slug"] and q in norm(r["slug"])):
            found.setdefault(r["slug"] or "-", []).append(r)
    known = set(found)
    extra = set()
    if os.path.isdir(store):
        extra = {e.name for e in entries(store) if not skip_name(e.name) and e.is_dir(follow_symlinks=False)}
        extra |= set(load_aliases(store))
    n = 0
    for slug, rs in sorted(found.items(), key=lambda kv: kv[1][0]["rank"]):
        for r in rs:
            print("%-22s #%-3d %s" % (slug, r["rank"], r["place"]))
            n += 1
    for slug in sorted(extra - known):
        if q in norm(slug):
            print("%-22s (no inventory row)" % slug)
            n += 1
    if n == 0:
        print("refs_store: no slug or place matches %r" % args.text)
        return 1
    return 0


# ---------------------------------------------------------------- sync

class Stats:
    def __init__(self):
        self.copied = self.skipped = self.conflicts = self.appended = 0


def append_missing_lines(src, dst):
    have = {ln.strip() for ln in read_lines(dst)}
    new = [ln for ln in read_lines(src) if ln.strip() and ln.strip() not in have]
    if not new:
        return 0
    with open(dst, "a", encoding="utf-8") as f:
        text = open(dst, encoding="utf-8").read() if os.path.getsize(dst) else ""
        if text and not text.endswith("\n"):
            f.write("\n")
        f.write("\n".join(new) + "\n")
    return len(new)


def sync_tree(src, dst, force, st, label):
    """Copy src into dst by the rules in the module docstring; never deletes."""
    os.makedirs(dst, exist_ok=True)
    for e in entries(src):
        if skip_name(e.name):
            continue
        d = os.path.join(dst, e.name)
        if e.is_dir(follow_symlinks=False):
            sync_tree(e.path, d, force, st, label + e.name + "/")
            continue
        if not e.is_file():
            continue
        if not os.path.exists(d):
            shutil.copyfile(e.path, d)
            st.copied += 1
            continue
        if e.name == "SOURCES.md":
            n = append_missing_lines(e.path, d)
            if n:
                st.appended += n
                print("  %s%s: appended %d lines" % (label, e.name, n))
            else:
                st.skipped += 1
            continue
        if os.path.getsize(e.path) == os.path.getsize(d):
            st.skipped += 1
            continue
        if force:
            shutil.copyfile(e.path, d)
            st.copied += 1
            print("  %s%s: overwritten (--force)" % (label, e.name))
        else:
            st.conflicts += 1
            print("  conflict: %s%s differs in size (%d vs %d), kept the destination" % (
                label, e.name, os.path.getsize(e.path), os.path.getsize(d)))


def sync_command(args, name):
    store = store_dir(args)
    repo = args.repo_refs or REPO_REFS
    if name == "pull":
        if not os.path.isdir(store):
            print("refs_store: no store at %s (set --store or REFS_STORE)" % store)
            return 1
        src_root, dst_root = store, repo
    else:
        src_root, dst_root = repo, store
    if args.all:
        slugs = [e.name for e in entries(src_root) if not skip_name(e.name) and e.is_dir(follow_symlinks=False)]
    else:
        slugs = list(args.slugs_list)
    if not slugs:
        print("refs_store: %s: give SLUG... or --all" % name)
        return 1
    if name == "push":
        os.makedirs(store, exist_ok=True)
    st, missing = Stats(), []
    for slug in slugs:
        if not SLUG_RE.match(slug):
            print("refs_store: %s: not a slug: %r" % (name, slug))
            missing.append(slug)
            continue
        src = os.path.join(src_root, slug)
        if not os.path.isdir(src):
            print("refs_store: %s: no folder %s" % (name, src))
            missing.append(slug)
            continue
        print("%s %s" % (name, slug))
        sync_tree(src, os.path.join(dst_root, slug), args.force, st, slug + "/")
    print("refs_store: %s: %d folders, %d copied, %d skipped, %d conflicts, %d SOURCES.md lines appended%s" % (
        name, len(slugs) - len(missing), st.copied, st.skipped, st.conflicts, st.appended,
        (", %d missing" % len(missing)) if missing else ""))
    code = 1 if missing else 0
    if name == "push":
        code = max(code, cmd_index(args))
    return code


